    public class PluginConfiguration : BasePluginConfiguration
    {
        // All editor settings as JSON. The field list in Web/editor.js is the schema, so adding an option
        // needs no C# change.
        public string SettingsJson { get; set; } = "";

        // The finished stylesheet, generated by the editor and served as-is by /ThemeBuilder/style.css.
        public string GeneratedCss { get; set; } = "";

        // Plugin version that generated GeneratedCss. When it differs from the running version, the first
        // administrator to open the web client rebuilds the CSS (and the TV copy) from SettingsJson.
        public string CssVersion { get; set; } = "";

        // The settings before the last save, for "Restore previous save".
        public string PreviousSettingsJson { get; set; } = "";
    }

    public class Plugin : BasePlugin<PluginConfiguration>, IHasWebPages
    {
        // Also handed to editor.js (it loads/saves this plugin's configuration by id).
        public const string PluginGuid = "fa3e0346-a82a-4dc0-a3dc-c20146da6cee";

        // Assembly version (from the csproj) as "major.minor.patch".
        public static readonly string VersionText = typeof(Plugin).Assembly.GetName().Version?.ToString(3) ?? "0.0.0";

        public override string Name => "Theme Builder";
        public override Guid Id => Guid.Parse(PluginGuid);

        public static Plugin Instance { get; private set; } = null!;

        private static ILogger? _logger;

        public Plugin(IApplicationPaths appPaths, IXmlSerializer xmlSerializer, ILogger<Plugin> logger) 
            : base(appPaths, xmlSerializer) 
        {
            Instance = this;
            _logger = logger;
        }

        public static string InjectThemeEditorScript(PatchRequestPayload payload)
        {
            string originalHtml = payload?.Contents ?? "";
            try
            {
                if (string.IsNullOrWhiteSpace(originalHtml))
                {
                    _logger?.LogWarning("[ThemeBuilder] InjectThemeEditorScript received empty contents; nothing was injected.");
                    return originalHtml;
                }

                if (originalHtml.Contains("ThemeBuilder/editor.js")) return originalHtml;

                // Only ever touch a real HTML document, never a script or other asset.
                if (originalHtml.IndexOf("</head>", StringComparison.OrdinalIgnoreCase) < 0
                    || originalHtml.IndexOf("</body>", StringComparison.OrdinalIgnoreCase) < 0)
                {
                    return originalHtml;
                }

                // index.html is served from {baseUrl}/web/, so go up one level to reach the API routes.
                // Relative (not "/ThemeBuilder/...") so it also works when Jellyfin has a base URL.
                // The saved theme is linked here too, so it applies without any Custom CSS setup.
                string html = originalHtml;
                string styleTag = "<link rel=\"stylesheet\" href=\"../ThemeBuilder/style.css\">";
                int headEnd = html.LastIndexOf("</head>", StringComparison.OrdinalIgnoreCase);
                html = html.Insert(headEnd, styleTag);

                string scriptTag = "<script defer src=\"../ThemeBuilder/editor.js\"></script>";
                int bodyEnd = html.LastIndexOf("</body>", StringComparison.OrdinalIgnoreCase);
                return html.Insert(bodyEnd, scriptTag);
            }
            catch (Exception ex)
            {
                _logger?.LogError(ex, "[ThemeBuilder] InjectThemeEditorScript threw while transforming index.html.");
                // Never blank out index.html on failure.
                return originalHtml;
            }
        }

        public IEnumerable<PluginPageInfo> GetPages()
        {
            return new[]
            {
                new PluginPageInfo
                {
                    Name = this.Name,
                    EmbeddedResourcePath = "JellyfinThemeBuilder.Configuration.configPage.html",
                    EnableInMainMenu = true,
                    MenuIcon = "brush" 
                }
            };
        }
    }

    // TV apps only get the theme through the server's Custom CSS (Dashboard > General), which the editor keeps a
    // marked copy of on every save. If that copy goes missing (Custom CSS cleared or edited, a config backup
    // restored), TV apps lose the theme until the next save; this puts the saved theme back.
    public static class BrandingSync
    {
        // Must match BRAND_START / BRAND_END in Web/editor.js.
        public const string Start = "/* ThemeBuilder:start (managed by the Theme Builder plugin; edits here are overwritten) */";
        public const string End = "/* ThemeBuilder:end */";

        // An @import statement, or a comment so that an @import inside a comment is left alone.
        // Must match IMPORT_OR_COMMENT in Web/editor.js.
        private static readonly Regex ImportOrComment = new Regex(
            "/\\*[\\s\\S]*?\\*/|@import\\s+(?:url\\(\\s*(?:'[^']*'|\"[^\"]*\"|[^)]*)\\s*\\)|'[^']*'|\"[^\"]*\")[^;]*;\\s*");

        // The Custom CSS with the saved theme in its marked block and the rest kept, the admin's own @import lines
        // first (browsers ignore an @import after any other rule); null when it already matches (or there's no saved
        // theme yet). Must give the same result as mergeBrandingCss in Web/editor.js.
        public static string? Merge(string? existing, string? css)
        {
            if (string.IsNullOrWhiteSpace(css)) return null;
            string rest = existing ?? "";
            int s = rest.IndexOf(Start, StringComparison.Ordinal);
            int e = s < 0 ? -1 : rest.IndexOf(End, s, StringComparison.Ordinal);
            if (s >= 0 && e > s) rest = rest.Substring(0, s) + rest.Substring(e + End.Length);
            // The manual @import from older versions is redundant, as in the editor.
            rest = Regex.Replace(rest, "@import url\\(['\"]?/ThemeBuilder/style\\.css['\"]?\\);?\\s*", "");
            var imports = new List<string>();
            rest = ImportOrComment.Replace(rest, m =>
            {
                if (m.Value.StartsWith("/*", StringComparison.Ordinal)) return m.Value;
                imports.Add(m.Value.Trim());
                return "";
            }).Trim();
            string merged = (imports.Count > 0 ? string.Join("\n", imports) + "\n\n" : "")
                + Start + "\n" + css + "\n" + End + (rest.Length > 0 ? "\n\n" + rest : "");
            // Compare ignoring line endings and outer whitespace, which the config file may not keep exactly.
            static string Norm(string x) => x.Replace("\r\n", "\n").Trim();
            return Norm(merged) == Norm(existing ?? "") ? null : merged;
        }
    }

    public class ThemeBuilderStartup : IHostedService
    {
        private readonly ILogger<ThemeBuilderStartup> _logger;
        private readonly IServerConfigurationManager _config;

        public ThemeBuilderStartup(ILogger<ThemeBuilderStartup> logger, IServerConfigurationManager config)
        {
            _logger = logger;
            _config = config;
        }

        private void RestoreBrandingCopy()
        {
            try
            {
                string? css = Plugin.Instance?.Configuration.GeneratedCss;
                var branding = _config.GetConfiguration<BrandingOptions>("branding");
                string? merged = BrandingSync.Merge(branding.CustomCss, css);
                if (merged == null) return;
                branding.CustomCss = merged;
                _config.SaveConfiguration("branding", branding);
                _logger.LogInformation("[ThemeBuilder] The theme's copy in Custom CSS (used by TV apps) was missing or out of date; restored it from the saved theme.");
            }
            catch (Exception ex)
            {
                _logger.LogWarning(ex, "[ThemeBuilder] Could not check the theme's copy in Custom CSS.");
            }
        }

        // How long to keep retrying the File Transformation registration (see RegisterWithRetriesAsync).
        private const int RegisterAttempts = 60;
        private static readonly TimeSpan RegisterRetryDelay = TimeSpan.FromSeconds(2);
        private int _lastCopyCount;

        public Task StartAsync(CancellationToken cancellationToken)
        {
            RestoreBrandingCopy();

            _logger.LogInformation("[ThemeBuilder] Server booted. Registering global script with File Transformation.");
            // Not awaited: startup mustn't wait for the retries.
            _ = Task.Run(RegisterWithRetriesAsync);
            return Task.CompletedTask;
        }

        // File Transformation 3.x resolves its services from the provider it was created with. Jellyfin can load it more
        // than once during startup, and a copy whose provider is already disposed throws ObjectDisposedException inside
        // RegisterTransformation, so the script was never injected. Keep checking for the whole window and register once
        // with every copy that accepts, since the copy that serves pages may only appear after an earlier one accepted.
        private async Task RegisterWithRetriesAsync()
        {
            Exception? lastError = null;
            for (int attempt = 1; attempt <= RegisterAttempts; attempt++)
            {
                // null: File Transformation is missing or incompatible; retrying won't change that.
                if (TryRegister(out Exception? error) == null) return;
                if (error != null) lastError = error;
                if (attempt == 1 && _registered.Count == 0)
                {
                    _logger.LogInformation("[ThemeBuilder] File Transformation isn't ready yet ({Copies} loaded copies; {Reason}); retrying until it is.",
                        _lastCopyCount, error?.GetBaseException().Message);
                }
                await Task.Delay(RegisterRetryDelay).ConfigureAwait(false);
            }
            if (_registered.Count == 0)
            {
                _logger.LogError(lastError, "[ThemeBuilder] Could not register with File Transformation after {Attempts} attempts. " +
                    "The theme editor and script features won't load until Jellyfin is restarted.", RegisterAttempts);
            }
        }

        // File Transformation copies already registered with (see RegisterWithRetriesAsync).
        private readonly HashSet<System.Reflection.Assembly> _registered = new();

        // Registers with every loaded File Transformation copy not registered yet. false: none of them accepted this time
        // (error says why; a later try may work). null: File Transformation isn't usable at all. true otherwise.
        private bool? TryRegister(out Exception? error)
        {
            error = null;
            string json = JsonSerializer.Serialize(new
            {
                id = "7c1e2b9a-4d3f-4a8e-9b61-5f2d8c0e1a47",
                // Must be exactly "index.html". File Transformation groups transformations by this string and
                // runs only one group per file: an exact name match wins, and other plugins register
                // "index.html", so any other pattern here is never run for the real page.
                // The same group also runs (as a regex) on chunks like "itemDetails-index-html.<hash>.chunk.js";
                // InjectThemeEditorScript leaves anything that isn't a full HTML document untouched.
                fileNamePattern = "index.html",
                callbackAssembly = typeof(Plugin).Assembly.FullName,
                callbackClass = typeof(Plugin).FullName,
                callbackMethod = nameof(Plugin.InjectThemeEditorScript)
            });

            // Jellyfin can load File Transformation more than once during startup (each copy with its own static
            // Instance), and the first copy found may be the one whose services were disposed: registering there
            // throws every time. Try every loaded copy, newest first, until one accepts.
            var candidates = AssemblyLoadContext.All.SelectMany(c => c.Assemblies)
                .Concat(AppDomain.CurrentDomain.GetAssemblies())
                .Where(a => a.FullName != null && a.FullName.Contains(".FileTransformation"))
                .Distinct()
                .Reverse()
                .ToList();
            if (candidates.Count == 0)
            {
                _logger.LogWarning("[ThemeBuilder] File Transformation plugin assembly not found in the loaded assembly list. " +
                    "Is it installed and did it load successfully? (A crash in an unrelated plugin during boot can prevent " +
                    "other plugins' assemblies from ever loading, which will land you here silently.)");
                return null;
            }

            _lastCopyCount = candidates.Count;
            bool anyUsable = false;
            foreach (var ftAssembly in candidates)
            {
                var registerMethod = ftAssembly.GetType("Jellyfin.Plugin.FileTransformation.PluginInterface")?.GetMethod("RegisterTransformation");
                var parameters = registerMethod?.GetParameters();
                if (registerMethod == null || parameters == null || parameters.Length != 1) continue;
                anyUsable = true;
                if (_registered.Contains(ftAssembly)) continue;
                try
                {
                    // File Transformation expects a Newtonsoft JObject. Build it with the JObject type this copy was
                    // compiled against (its own parameter type), so no compile-time Newtonsoft reference is needed
                    // and a second Newtonsoft copy can't cause a type mismatch.
                    var parseMethod = parameters[0].ParameterType.GetMethod("Parse", new[] { typeof(string) });
                    if (parseMethod == null) continue;
                    var payload = parseMethod.Invoke(null, new object[] { json });
                    registerMethod.Invoke(null, new object?[] { payload });
                    _registered.Add(ftAssembly);
                    _logger.LogInformation("[ThemeBuilder] Successfully registered script injection (File Transformation copy {Index} of {Count}, load context {Context}).",
                        candidates.IndexOf(ftAssembly) + 1, candidates.Count, AssemblyLoadContext.GetLoadContext(ftAssembly)?.Name);
                }
                catch (Exception ex)
                {
                    error = ex;
                }
            }

            if (!anyUsable)
            {
                _logger.LogWarning("[ThemeBuilder] File Transformation was found but its PluginInterface.RegisterTransformation was not. " +
                    "It may be an incompatible version.");
                return null;
            }
            return _registered.Count > 0;
        }

        public Task StopAsync(CancellationToken cancellationToken) => Task.CompletedTask;
    }

